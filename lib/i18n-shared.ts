export const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, fr, ar }

function interpolate(str: string, vars?: Record<string, string | number>): string {
  if (!vars) return str
  return str.replace(/\{(\w+)\}/g, (match, key) => (key in vars ? String(vars[key]) : match))
}

export function translate(locale: Locale, key: TranslationKey, vars?: Record<string, string | number>): string {
  return interpolate(dictionaries[locale][key], vars)
}
